func optS(short, desc string) Flag { return Flag{Short: short, Desc: desc} }

func optSV(short, desc string) Flag { return Flag{Short: short, Desc: desc, Value: true} }

func optL(long, desc string) Flag { return Flag{Long: long, Desc: desc} }

func optLV(long, desc string) Flag { return Flag{Long: long, Desc: desc, Value: true} }

func optLS(long, short, desc string) Flag { return Flag{Long: long, Short: short, Desc: desc} }

func optLSV(long, short, desc string) Flag {
	return Flag{Long: long, Short: short, Desc: desc, Value: true}
}

