// The Carapace snapshot is a curated set of 700-odd commands. Whole families
// that people type on a Linux server every day are simply missing from it:
// net-tools (netstat, ifconfig, route, arp), iproute2 (ip, ss, tc, nft), packet
// capture, the database clients, and the POSIX shell builtins. Essentials fills
// those gaps by hand, with the options that are actually used, so a prefix like
// "netstat -" has something to say.
//
// Essentials is a second catalog, consulted only when the main catalog has no
// root for the command. Keeping it separate means a regenerated Carapace
// snapshot never has to be edited by hand, and a command both catalogs know is
// still answered by the richer imported syntax.

var (
	essentialsOnce sync.Once
	essentials     *Catalog
)

// Essentials returns the hand-maintained catalog. It is built once; a nil
// result means the table itself is broken, which the tests guard against.
func Essentials() *Catalog {
	essentialsOnce.Do(func() {
		essentials, _ = newCatalogInOrder(
			"motty-essentials", "1", "hand-written", "Motty", essentialRoots(),
		)
	})
	return essentials
}

// newCatalogInOrder is NewCatalog without the alphabetical sort. The imported
// catalog has no hand-written order to preserve, so sorting it keeps the
// snapshot deterministic; this table does, and the order is the one people
// reach for first (netstat's -t and -u before -W). Flags are still indexed and
// validated exactly like any other catalog.
func newCatalogInOrder(source, release, commit, license string, roots []*Node) (*Catalog, error) {
	c := &Catalog{
		Source:  source,
		Release: release,
		Commit:  commit,
		License: license,
		index:   make(map[string]*Node, 512),
	}
	for _, root := range roots {
		if err := c.indexTree(root, nil); err != nil {
			return nil, err
		}
	}
	if len(c.roots) == 0 {
		return nil, errors.New("completion: catalog has no root commands")
	}
	c.count()
	return c, nil
}

